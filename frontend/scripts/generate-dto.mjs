#!/usr/bin/env node
/**
 * Writes lib/api/generated.ts from the local API's contract.
 *
 * The contract is `python -m repoatlas.api.schema`: one JSON Schema per request
 * and response, each its own root with its own `$defs`. They are merged into one
 * set of definitions (a name defined twice must be defined identically, or this
 * fails) and compiled once, so every endpoint shares one `RepositoryRef`, one
 * `CapabilityError` and so on.
 *
 *   pnpm dto          regenerate
 *   pnpm dto:check    fail if the committed file differs from the contract
 *
 * REPOATLAS_PYTHON names the interpreter; by default the repository's .venv.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repository = path.resolve(app, "..");
const target = path.join(app, "lib/api/generated.ts");
const checking = process.argv.includes("--check");

function readContract() {
  const python = process.env.REPOATLAS_PYTHON ?? path.join(repository, ".venv/bin/python");
  const output = execFileSync(python, ["-m", "repoatlas.api.schema"], {
    cwd: repository,
    encoding: "utf8",
    maxBuffer: 64 << 20,
  });
  return JSON.parse(output);
}

/** Schema keywords whose values are schemas, or maps or lists of schemas. */
const SCHEMA = new Set(["items", "additionalProperties", "not", "if", "then", "else", "contains"]);
const SCHEMA_LISTS = new Set(["anyOf", "oneOf", "allOf", "prefixItems"]);
const SCHEMA_MAPS = new Set(["properties", "patternProperties"]);

/**
 * Drops `title` from every nested schema. Pydantic titles each field ("Head Sha"),
 * which the compiler would turn into a named alias per field; only definitions
 * are meant to be named.
 *
 * A `$ref` keeps nothing beside it. Pydantic writes a field's default next to
 * its reference (`{"$ref": "#/$defs/FreshnessDepth", "default": "live"}`), which
 * the compiler reads as a new schema and declares again as `FreshnessDepth1`.
 * A default has no TypeScript form, so the plain reference loses nothing.
 */
function untitled(schema) {
  if (typeof schema !== "object" || schema === null) return schema;
  if (typeof schema.$ref === "string") return { $ref: schema.$ref };
  const copy = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === "title") continue;
    if (SCHEMA.has(key)) copy[key] = untitled(value);
    else if (SCHEMA_LISTS.has(key)) copy[key] = value.map(untitled);
    else if (SCHEMA_MAPS.has(key))
      copy[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, untitled(v)]));
    else copy[key] = value;
  }
  return copy;
}

function mergeDefinitions(contract) {
  const definitions = new Map();
  const define = (name, schema) => {
    const text = JSON.stringify(schema);
    const known = definitions.get(name);
    if (known !== undefined && JSON.stringify(known) !== text) {
      throw new Error(`the contract defines ${name} twice, differently`);
    }
    definitions.set(name, schema);
  };
  const root = (schema) => {
    const { $defs = {}, title, ...rest } = schema;
    for (const [name, definition] of Object.entries($defs)) {
      define(name, { ...untitled(definition), title: name });
    }
    define(title, { ...untitled(rest), title });
    return title;
  };
  const endpoints = contract.endpoints.map((endpoint) => ({
    name: endpoint.name,
    request: root(endpoint.request),
    response: root(endpoint.response),
  }));
  const index = root(contract.index.response);
  const error = root(contract.error);
  return { definitions, endpoints, index, error };
}

async function generate() {
  const contract = readContract();
  const { definitions, endpoints, index } = mergeDefinitions(contract);
  const { [index]: indexSchema, ...rest } = Object.fromEntries(
    [...definitions.entries()].sort(([a], [b]) => a.localeCompare(b)),
  );
  const types = await compile({ ...indexSchema, $defs: rest }, index, {
    bannerComment: [
      "/* eslint-disable */",
      "/**",
      " * Generated by scripts/generate-dto.mjs from `python -m repoatlas.api.schema`.",
      " * Do not edit: run `pnpm dto` after the contract changes.",
      " */",
    ].join("\n"),
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    style: { singleQuote: false, printWidth: 100, trailingComma: "all" },
  });
  const map = endpoints
    .map((e) => `  ${JSON.stringify(e.name)}: { request: ${e.request}; response: ${e.response} };`)
    .join("\n");
  return `${types}
export const CONTRACT = ${JSON.stringify(contract.contract)} as const;

/** Every endpoint the local API serves, in the server's registry order. */
export const ENDPOINT_NAMES = ${JSON.stringify(endpoints.map((e) => e.name))} as const;

export type EndpointName = (typeof ENDPOINT_NAMES)[number];

/** Each endpoint's request body and the \`result\` of its success envelope. */
export interface Endpoints {
${map}
}
`;
}

const generated = await generate();
if (checking) {
  const committed = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (committed !== generated) {
    console.error("lib/api/generated.ts differs from the local API's contract: run `pnpm dto`.");
    process.exit(1);
  }
  console.log("lib/api/generated.ts matches the contract.");
} else {
  writeFileSync(target, generated);
  console.log(`wrote ${path.relative(app, target)}`);
}
